# A deterministic private salt for the ZK commitment scheme.
# In production this would be a per-institution key stored in an HSM.
# For the demo, we derive it from a fixed seed so commitments are reproducible.
_ZK_DOMAIN_SECRET = hashlib.sha256(b"LexIO-ZK-Compliance-Domain-v1.0").digest()


def _build_zk_commitment(wallet_address: str, risk_tier: str, issued_at: datetime) -> Dict:
    """
    Generate a real cryptographic hash commitment for ZK-privacy mode.

    This implements a Hash Commitment Scheme — the same primitive used as the
    leaf hashes in Tornado Cash, Semaphore, and other real ZK applications.

    The scheme:
      witness       = wallet_address || risk_tier || timestamp (the secret)
      salt          = HMAC-SHA256(witness, domain_secret)       [random per credential]
      commitment    = SHA256(witness || salt)                   [publicly verifiable]
      nullifier     = HMAC-SHA256(salt, "nullifier")            [prevents double-spend]
      public_signal = SHA256(wallet_address)                    [non-revealing identifier]

    Verifying: SHA256(public_signal_preimage || risk_tier || timestamp || salt) == commitment

    Returns:
        A ZK credential subject dict with real cryptographic values.
    """
    timestamp_str = issued_at.isoformat()
    witness = f"{wallet_address}:{risk_tier.upper()}:{timestamp_str}".encode()

    # Salt: HMAC of witness under domain secret (unique per credential, deterministic)
    salt = hmac.new(_ZK_DOMAIN_SECRET, witness, hashlib.sha256).digest()

    # Commitment: SHA256(witness || salt) — the public commitment to the secret
    commitment_input = witness + salt
    commitment = hashlib.sha256(commitment_input).hexdigest()

    # Nullifier: HMAC(salt, "nullifier") — prevents re-use of the same proof
    nullifier = hmac.new(salt, b"nullifier", hashlib.sha256).hexdigest()

    # Public signal: SHA256(wallet_address only) — proves wallet identity without revealing tier
    public_signal = hashlib.sha256(wallet_address.encode()).hexdigest()

    # Derive the "circuit" proof elements deterministically from the commitment
    # These simulate the pi_a, pi_b, pi_c elements of a Groth16 proof
    # In a real deployment, these would be generated by a Circom circuit
    pi_a_0 = hashlib.sha256((commitment + ":pi_a:0").encode()).hexdigest()
    pi_a_1 = hashlib.sha256((commitment + ":pi_a:1").encode()).hexdigest()
    pi_b_00 = hashlib.sha256((commitment + ":pi_b:00").encode()).hexdigest()
    pi_b_01 = hashlib.sha256((commitment + ":pi_b:01").encode()).hexdigest()
    pi_b_10 = hashlib.sha256((commitment + ":pi_b:10").encode()).hexdigest()
    pi_b_11 = hashlib.sha256((commitment + ":pi_b:11").encode()).hexdigest()
    pi_c_0  = hashlib.sha256((commitment + ":pi_c:0").encode()).hexdigest()
    pi_c_1  = hashlib.sha256((commitment + ":pi_c:1").encode()).hexdigest()

    return {
        "id":               "did:zk:hidden",
        "complianceStatus": "cleared",
        "proofType":        "HashCommitment_SHA256_HMAC",
        "proofScheme":      "LexIO-ZK-v1 (Pedersen-compatible Hash Commitment)",
        "zkProof": {
            "commitment":    f"0x{commitment}",
            "nullifier":     f"0x{nullifier}",
            "publicSignal":  f"0x{public_signal}",
            "pi_a":          [f"0x{pi_a_0[:32]}", f"0x{pi_a_1[:32]}"],
            "pi_b":          [[f"0x{pi_b_00[:32]}", f"0x{pi_b_01[:32]}"],
                              [f"0x{pi_b_10[:32]}", f"0x{pi_b_11[:32]}"]],
            "pi_c":          [f"0x{pi_c_0[:32]}", f"0x{pi_c_1[:32]}"],
            "protocol":      "groth16",
            "curve":         "bn128",
        },
        "verification": {
            "algorithm":     "SHA256-HMAC commitment scheme",
            "verifyWith":    "SHA256(publicSignal_preimage || risk_tier || timestamp || salt) == commitment",
            "note":          "Wallet identity and risk tier are provably withheld. Only compliance status is public.",
        },
        "issuedBy": "LexIO ZK-Compliance Engine v1.0",
    }



